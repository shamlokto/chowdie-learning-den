#!/usr/bin/env python3
"""Inject (or refresh) the shared picture-book polish into every lesson deck.

Adds two marked blocks to each deck that uses the shared engine:
  * CSS  /* den-polish:start */ ... /* den-polish:end */  at the end of the head <style>
  * JS   <script id="den-fireworks"> ... </script>        just before </body>
Re-running replaces the blocks, so edit them here and run:  python3 tools/den-polish.py
Lesson and story content is never touched. Storybooks share the deck engine, so they get the same
blocks (a chapter counts as a stage for the fireworks). Pages without the engine (spelling/wordlists.html)
and the grown-ups deck are skipped. PHONE_CSS / apply_phone() hold just the phone layout, for any future
page that should not take the full look.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKIP = {"spelling/wordlists.html", "misc/discipline.html"}

CSS = r"""/* den-polish:start (shared look, generated by tools/den-polish.py) */
html{background:#EAF5EF}
body{background:transparent;background-image:none}
body::before{content:"";position:fixed;inset:0;z-index:-1;pointer-events:none;background:#EAF5EF url(../img/paper-wash.webp) center/cover no-repeat}
.eyebrow{display:inline-block;background:var(--paper);border:2px solid var(--accent-ink);border-radius:999px;padding:2px 12px 0}
.stage{box-shadow:0 7px 0 var(--ink),0 26px 40px -18px rgba(31,58,74,.4)}
.bubble{box-shadow:0 3px 0 rgba(31,58,74,.14)}
.parts button:not([aria-current="true"]):hover{background:#fff;transform:translateY(-1px)}
.foot{background:rgba(255,253,246,.8);border-radius:12px;padding:6px 12px;align-self:flex-start}
@media (max-width:520px){
 .wrap{padding-top:52px}
 .controls{gap:8px}
 .controls .dots{order:-1;flex:1 1 100%;padding:2px 0 4px}
 .controls>button{font-size:17px;padding:8px 14px 4px}
 .controls #next{margin-left:auto;padding-inline:20px}
 .talk{grid-template-columns:44px 1fr;gap:8px} .talk svg{width:44px;height:44px}
}
/* den-polish:end */
"""

PHONE_CSS = r"""/* den-phone:start (phone layout, generated by tools/den-polish.py) */
@media (max-width:520px){
 .wrap{padding-top:52px}
 .controls{gap:8px}
 .controls .dots{order:-1;flex:1 1 100%;padding:2px 0 4px}
 .controls>button{font-size:17px;padding:8px 14px 4px}
 .controls #next{margin-left:auto;padding-inline:20px}
 .talk{grid-template-columns:44px 1fr;gap:8px} .talk svg{width:44px;height:44px}
}
/* den-phone:end */
"""

JS = r"""<script id="den-fireworks">
/* Fireworks: a big show when a deck's final slide celebrates (deck done, Baddie Daddy beaten), a smaller one when
   the last slide of a stage celebrates (e.g. Baddie beaten) or the last quiz star of a stage is earned. Generated by tools/den-polish.py. */
(()=>{ if(typeof api!=='object'||typeof S==='undefined'||typeof render!=='function') return;
  const calm=matchMedia('(prefers-reduced-motion: reduce)').matches;
  const cols=['#FFB800','#FF6A2B','#2E9BE0','#2FA84F','#E83E6C','#8A55E0','#FF3B3B'];
  let cv=null, parts=[], rockets=[], until=0, start=0, raf=0, shown=-1;
  function show(big){ if(calm||document.hidden) return;
    if(!cv){cv=document.createElement('canvas');cv.setAttribute('aria-hidden','true');
      cv.style.cssText='position:fixed;inset:0;width:100vw;height:100vh;pointer-events:none;z-index:40';document.body.appendChild(cv);}
    const dpr=Math.min(devicePixelRatio||1,2);cv.width=innerWidth*dpr;cv.height=innerHeight*dpr;cv.getContext('2d').setTransform(dpr,0,0,dpr,0,0);
    const n=big?14:6, span=big?3200:1500, now=performance.now(); if(!raf) start=now;
    for(let k=0;k<n;k++) rockets.push({t:now+k*span/n+Math.random()*180,x:innerWidth*(.1+.8*Math.random()),y:innerHeight+10,
      ty:innerHeight*(.1+.35*Math.random()),c:cols[(Math.random()*7)|0],live:false});
    until=Math.max(until,now+span+2400); if(!raf) raf=requestAnimationFrame(tick); }
  function burst(r){ const m=80+(Math.random()*30|0), c2=cols[(Math.random()*7)|0], ring=Math.random()<.35, sc=Math.min(innerWidth,900)/900+.4;
    for(let k=0;k<m;k++){const a=k/m*Math.PI*2+Math.random()*.08, v=(ring?5.2:2+Math.random()*4.4)*sc;
      parts.push({x:r.x,y:r.y,vx:Math.cos(a)*v,vy:Math.sin(a)*v,life:1,c:k%3?r.c:c2,s:2.6+Math.random()*2,tw:Math.random()<.3});} }
  function tick(now){ const g=cv.getContext('2d'); g.clearRect(0,0,innerWidth,innerHeight);
    const fade=Math.min(1,(now-start)/400,Math.max(0,(until-now)/900)); g.fillStyle=`rgba(24,34,72,${.22*fade})`; g.fillRect(0,0,innerWidth,innerHeight);
    for(const r of rockets){ if(now<r.t) continue; if(!r.live){r.live=true;r.vy=-(innerHeight-r.ty)/42;}
      r.y+=r.vy; r.vy*=.985; g.fillStyle=r.c; g.beginPath(); g.arc(r.x,r.y,4,0,7); g.fill();
      g.fillStyle='rgba(255,184,0,.6)'; g.fillRect(r.x-1.5,r.y+5,3,16);
      if(r.y<=r.ty||r.vy>-1){burst(r);r.done=true;} }
    rockets=rockets.filter(r=>!r.done);
    for(const p of parts){ p.x+=p.vx; p.y+=p.vy; p.vx*=.975; p.vy=p.vy*.975+.045; p.life-=.0085;
      g.globalAlpha=Math.max(p.life,0)*(p.tw&&Math.random()<.4?.35:1); g.fillStyle=p.c; g.beginPath(); g.arc(p.x,p.y,p.s,0,7); g.fill();
      g.strokeStyle=p.c; g.lineWidth=2; g.beginPath(); g.moveTo(p.x,p.y); g.lineTo(p.x-p.vx*4,p.y-p.vy*4); g.stroke(); }
    g.globalAlpha=1; parts=parts.filter(p=>p.life>0);
    if(now<until||parts.length||rockets.length) raf=requestAnimationFrame(tick); else {raf=0; cv.remove(); cv=null;} }
  const last=()=>i===S.length-1;
  const stageDone=k=>{ const sc=S[k]; if(!sc||!sc.quiz) return false;
    const qs=S.map((s,j)=>j).filter(j=>S[j].part===sc.part&&S[j].quiz); return qs.length>1&&qs.every(j=>earned.has(j)); };
  const conf0=confetti, win0=win, render0=render;
  const partEnd=()=>!last()&&S[i+1]&&S[i+1].part!==S[i].part;
  confetti=function(){ conf0.apply(this,arguments); if((last()||partEnd())&&shown!==i){shown=i;show(last());} };
  win=function(){ const had=earned.has(i); win0.apply(this,arguments); if(!had&&earned.has(i)&&!last()&&stageDone(i)) show(false); };
  render=function(){ shown=-1; return render0.apply(this,arguments); };
  api.confetti=confetti; api.win=win;
  addEventListener('resize',()=>{ if(cv){const d=Math.min(devicePixelRatio||1,2);cv.width=innerWidth*d;cv.height=innerHeight*d;cv.getContext('2d').setTransform(d,0,0,d,0,0);} });
})();
</script>
"""

def apply_phone(path):
    s = path.read_text(encoding="utf-8")
    if "</style></head>" not in s:
        return "no-style"
    s = re.sub(r"/\* den-phone:start.*?/\* den-phone:end \*/\n", "", s, flags=re.S)
    k = s.index("</style></head>")
    path.write_text(s[:k].rstrip("\n") + "\n" + PHONE_CSS + s[k:], encoding="utf-8")
    return "phone"

def apply(path):
    rel = path.relative_to(ROOT).as_posix()
    s = path.read_text(encoding="utf-8")
    if "function drawDots" not in s or "const api=" not in s:
        return "no-engine"
    s = re.sub(r"/\* den-polish:start.*?/\* den-polish:end \*/\n", "", s, flags=re.S)
    s = re.sub(r'<script id="den-fireworks">.*?</script>\n', "", s, flags=re.S)
    s = re.sub(r"/\* den-phone:start.*?/\* den-phone:end \*/\n", "", s, flags=re.S)
    head_end = s.index("</style></head>")
    s = s[:head_end] + "\n" + CSS + s[head_end:]
    s = s.replace("\n\n" + CSS, "\n" + CSS)
    body_end = s.rindex("</body>")
    stars = s.rfind('<script src="../stars.js"', 0, body_end)  # keep the Star Bank script last
    at = stars if stars != -1 else body_end
    s = s[:at] + JS + s[at:]
    path.write_text(s, encoding="utf-8")
    return "ok"

if __name__ == "__main__":
    for p in sorted(ROOT.glob("*/*.html")):
        rel = p.relative_to(ROOT).as_posix()
        if rel in SKIP:
            continue
        print(apply(p), rel)
