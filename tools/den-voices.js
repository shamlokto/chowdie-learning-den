#!/usr/bin/env node
/* Pre-made character voices (xAI text-to-speech), so the characters sound the same on every device.

   node tools/den-voices.js stories/dash-adv.html [more decks...]     (JOBS=6 decks at a time)

   Mixed English/Chinese lines are split into parts and each part gets its own clip, sent to xAI as Chinese or
   English (one clip of mixed text can come out in the wrong language); the player plays the parts in order.
   For each deck it:
     1. opens the deck headlessly and records every line it says (all slides with read-aloud on, plus every
        button and tappable Chinese word on each slide, through every quiz round), as (who, text) pairs;
     2. makes one MP3 per new line with that character's xAI voice (CAST below), shaped with ffmpeg
        (pitch/tempo, 40 kbps mono), into audio/<deck>/<key>.mp3 (PRUNE=1 also deletes clips no longer said);
     3. writes audio/<deck>.js (the list of clips) and adds the den-audio player block to the deck.
   The deck plays a clip when it has one and falls back to the device voice otherwise (lines built on the
   fly, a deck without clips), so it is safe to re-run after any wording change: only new lines cost money.
   REDO=<text> remakes the clips whose line contains that text (e.g. after changing a voice or a spoken() rule).
   DRY=1 lists the lines and their cost without calling xAI.
   Needs XAI_API_KEY in the environment (never written anywhere), ffmpeg, curl and Playwright. */
const fs = require('fs'), path = require('path'), os = require('os'), {execFile} = require('child_process');
const run = (cmd, args, input) => new Promise((ok, bad) => { const c = execFile(cmd, args, (e, so, se) => e ? bad(new Error(cmd + ': ' + (se || e.message).toString().slice(0, 300))) : ok()); c.stdin.end(input || ''); });
const {chromium} = require(fs.existsSync('/opt/node-tools/node_modules/playwright') ? '/opt/node-tools/node_modules/playwright' : 'playwright');

const ROOT = path.resolve(__dirname, '..');
/* who -> xAI voice; pitch >1 is higher (and younger), tempo is the speaking speed after the pitch change. */
const CAST = {
  wala:   {voice: 'eve',    pitch: 1.19, tempo: 1.05},  // little koala: young and bouncy
  flame:  {voice: 'luna',   pitch: 1.08, tempo: 1.0},
  mommy:  {voice: 'ara',    pitch: 1.0,  tempo: 0.97},
  otter:  {voice: 'leo',    pitch: 1.0,  tempo: 1.0},   // Chowdie, also the narrator
  owl:    {voice: 'orion',  pitch: 0.94, tempo: 0.93},  // Immortal Dash: wise, unhurried
  eagle:  {voice: 'helios', pitch: 0.97, tempo: 1.0},
  baddie: {voice: 'zagan',  pitch: 0.86, tempo: 0.92},
  daddy:  {voice: 'atlas',  pitch: 0.78, tempo: 0.88},  // Baddie Daddy keeps his big funny growl
};
const FALLBACK = 'otter';

/* The player. denSay() plays a line's clips (a mixed line plays its English and Chinese parts in order) and falls
   back to the device voice when any part has no clip. HOOK_NOW wraps speakNow() in character decks; HOOK_NARR wraps
   speak() in narrator-only decks (P2 maths, life science...), which Chowdie narrates. */
const CORE = String.raw`/* den-audio:start (pre-made character voices, generated by tools/den-voices.js) */
var DEN_A=null, DEN_T=0, DEN_CJK=/([⺀-鿿　-〿＀-￯]+)/;
function denKey(who,s){let h=2166136261;const k=who+'|'+s;for(let n=0;n<k.length;n++){h^=k.charCodeAt(n);h=Math.imul(h,16777619)}return (h>>>0).toString(36)}
/* a mixed line becomes English and Chinese parts (one clip each), as the device voices split it */
function denParts(s){const parts=s.split(DEN_CJK).map(p=>p.trim()).filter(p=>/[\p{L}\p{N}]/u.test(p));
  for(let k=parts.length-2;k>0;k--) if(/^[\s\dA-Z%.:,-]+$/.test(parts[k])&&DEN_CJK.test(parts[k-1])&&DEN_CJK.test(parts[k+1])) parts.splice(k-1,3,parts[k-1]+parts[k]+parts[k+1]);
  return parts;}
function denStop(){DEN_T++;if(DEN_A)try{DEN_A.pause()}catch(e){}}
function denSay(s,who,device){
  s=s.replace(/\s+/g,' ').trim(); denStop(); const parts=denParts(s); if(!parts.length) return;
  if(window.__denCap) parts.forEach(p=>window.__denCap.push({who,s:p}));
  const clips=window.DEN_AUDIO, ks=parts.map(p=>denKey(who,p));
  if(!clips||!ks.every(k=>clips.has(k))) return device();
  try{VTOK++;speechSynthesis.cancel()}catch(e){}
  if(!DEN_A) DEN_A=new Audio();
  const tok=DEN_T; let n=0;
  const next=()=>{if(tok!==DEN_T||n>=ks.length) return; DEN_A.src=window.DEN_AUDIO_DIR+ks[n++]+'.mp3'; const p=DEN_A.play(); if(p&&p.catch) p.catch(()=>{if(n===1&&tok===DEN_T) device()})};
  DEN_A.onended=next; next();
}`;
const HOOK_NOW = String.raw`
const speakDevice=speakNow;
speakNow=function(t,who=WHO){denSay(t.replace(/<i class="py">.*?<\/i>/g,' ').replace(/<[^>]+>/g,' ').replace(/ℓ/g,' litres'),who,()=>speakDevice(t,who))};
/* den-audio:end */`;
const HOOK_NARR = String.raw`
const speakDevice=speak;
speak=function(t){ if(!reading) return; denSay(t.replace(/<[^>]+>/g,' ').replace(/ℓ/g,' litres').replace(/\bkg\b/g,'kilograms').replace(/\bmin\b/g,'minutes'),'otter',()=>speakDevice(t)); };
/* den-audio:end */`;
const NOW_AT = '\nspeak=function(t){ if(reading) speakNow(t); };', NARR_AT = '\nfunction say(t){ sayEl.innerHTML=t; speak(t); }';

/* What the voice is sent (the clip key still uses the deck's own text): no emoji, and "速 = fast" read as "速 means fast". */
const spoken = t => t.replace(/[\p{Extended_Pictographic}\uFE0F]/gu, '').replace(/\s*=\s*/g, ' means ').replace(/\s+/g, ' ').trim();

async function curlTts(text, voice, out) {
  const body = out + '.json';
  fs.writeFileSync(body, JSON.stringify({text: spoken(text), voice_id: voice, language: /[⺀-鿿　-〿＀-￯]/.test(text) ? 'zh' : 'en'}));
  try {
    await run('curl', ['-sS', '-f', '-m', '90', '--retry', '3', '--retry-all-errors', '-o', out, '-H', '@-', '-H', 'Content-Type: application/json',
      '--data-binary', '@' + body, 'https://api.x.ai/v1/tts'], `Authorization: Bearer ${process.env.XAI_API_KEY}\n`);
  } finally { fs.rmSync(body, {force: true}); }
}

function shape(src, dst, {pitch, tempo}) {
  const af = pitch === 1 ? `atempo=${tempo}` : `asetrate=24000*${pitch},aresample=24000,atempo=${(tempo / pitch).toFixed(4)}`;
  return run('ffmpeg', ['-loglevel', 'error', '-y', '-i', src, '-af', af, '-ac', '1', '-b:a', process.env.BITRATE || '40k', dst]);
}

/* The same key the player computes in the page (FNV-1a of who|text, base 36). */
function denKey(who, s) { let h = 2166136261; const k = who + '|' + s; for (let n = 0; n < k.length; n++) { h ^= k.charCodeAt(n); h = Math.imul(h, 16777619); } return (h >>> 0).toString(36); }

/* Play the deck headlessly with read-aloud on and record every line it would say. Timers run on a fake clock, so
   each quiz can be played through all its rounds (rounds move on after a delay) without real waiting. */
async function capture(browser, deck) {
  const ctx = await browser.newContext(), p = await ctx.newPage();
  await p.route('https://script.google.com/**', r => r.abort());
  await p.route('https://cdn.jsdelivr.net/**', r => r.abort());
  // lines go straight to the tool, and buttons that leave the deck (links, restarts) are blocked, so nothing is lost
  const got = [], url = 'file://' + path.join(ROOT, deck);
  await p.exposeFunction('__denPush', l => { got.push(l); });
  await p.route(u => u.protocol === 'file:', r => (r.request().isNavigationRequest() && r.request().frame() === p.mainFrame() && r.request().url().split('#')[0] !== url) ? r.abort() : r.continue());
  await p.addInitScript(() => {
    window.__denCap = {push: l => window.__denPush(l)}; window.SpeechSynthesisUtterance = function (t) { this.text = t; };
    const ss = window.speechSynthesis;
    for (const [k, v] of [['getVoices', () => []], ['speak', () => {}], ['cancel', () => {}]]) Object.defineProperty(ss, k, {value: v});
    HTMLMediaElement.prototype.play = function () { return Promise.resolve(); };
  });
  await p.clock.install();
  // a timer that throws (e.g. hanzi-writer without its CDN) stops runFor; skip past it and keep the clock going
  const tick = async ms => { for (let i = 0; i < 30; i++) { try { await p.clock.runFor(ms); return; } catch (e) {} } };
  await p.goto(url);
  await tick(500);
  await p.evaluate(() => { window.DEN_AUDIO = null; const b = document.getElementById('read'); if (b && b.getAttribute('aria-pressed') !== 'true') b.click(); });
  const n = await p.evaluate(() => document.querySelectorAll('#dots button').length);
  const count = async () => got.length;
  for (let k = 0; k < n; k++) {
    await p.evaluate(k => document.querySelectorAll('#dots button')[k].click(), k);
    await tick(400);
    for (let round = 0; round < 8; round++) {  // tap everything, let the round move on, repeat while new lines appear
      const before = await count();
      await p.evaluate(() => {
        document.querySelectorAll('#stage [data-zh]').forEach(g => g.dispatchEvent(new MouseEvent('click', {bubbles: true})));
        document.querySelectorAll('#ui button, #stage button').forEach(b => { try { b.click(); } catch (e) {} });
      });
      await tick(3500);
      if (await count() === before) break;
    }
  }
  const keyed = got.map(l => ({...l, k: denKey(l.who, l.s)}));  // the page may have left the deck by now
  await ctx.close();
  const uniq = new Map(); for (const l of keyed) if (l.s) uniq.set(l.k, l);
  return [...uniq.values()];
}

let chars = 0, made = 0;
async function doDeck(browser, deck) {
  const file = path.join(ROOT, deck);
  let html = fs.readFileSync(file, 'utf8');
  const id = path.basename(deck, '.html'), dir = path.join(ROOT, 'audio', id), rel = path.relative(path.dirname(file), path.join(ROOT, 'audio'));
  // player block + clip list tag (idempotent)
  html = html.replace(/\n\/\* den-audio:start[\s\S]*?den-audio:end \*\//, '');
  if (html.includes(NOW_AT)) html = html.replace(NOW_AT, '\n' + CORE + HOOK_NOW + NOW_AT);
  else if (html.includes(NARR_AT)) html = html.replace(NARR_AT, NARR_AT + '\n' + CORE + HOOK_NARR);
  else throw new Error(deck + ': no place for the player (no speakNow or say/speak engine)');
  html = html.replace('try{VTOK++;speechSynthesis.cancel()}catch(e){}', 'try{VTOK++;speechSynthesis.cancel();denStop()}catch(e){}');
  html = html.replace('else try{speechSynthesis.cancel()}catch(x){}', 'else try{speechSynthesis.cancel();denStop()}catch(x){}');
  const tag = `<script src="${rel}/${id}.js"></script>`;
  html = html.replace(tag + '</head>', '</head>');  // keep </style></head> intact for den-polish.py
  if (!html.includes(tag)) html = html.replace('</head><body>', '</head><body>\n' + tag);
  // DRY works on a scratch copy next to the deck, so the deck itself is untouched
  const target = process.env.DRY ? deck.replace(/\.html$/, '.dry.html') : deck;
  fs.writeFileSync(path.join(ROOT, target), html);

  // answers are shuffled, so different taps reveal different feedback lines: capture twice
  const seen = new Map();
  try { for (let pass = 0; pass < 2; pass++) for (const l of await capture(browser, target)) seen.set(l.k, l); }
  finally { if (process.env.DRY) fs.unlinkSync(path.join(ROOT, target)); }
  const lines = [...seen.values()];
  if (process.env.DRY) { const c = lines.reduce((n, l) => n + l.s.length, 0); chars += c; made += lines.length; console.log(`${deck}: ${lines.length} lines, ${c} chars`); return; }
  fs.mkdirSync(dir, {recursive: true});
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'den-voices-'));
  for (const l of lines) {
    const out = path.join(dir, l.k + '.mp3');
    if (fs.existsSync(out) && !(process.env.REDO && l.s.includes(process.env.REDO))) continue;
    const cast = CAST[l.who] || CAST[FALLBACK], raw = path.join(tmp, l.k + '.mp3');
    await curlTts(l.s, cast.voice, raw); await shape(raw, out, cast);
    fs.unlinkSync(raw);
    chars += l.s.length; made++;
  }
  fs.rmdirSync(tmp);
  const said = new Set(lines.map(l => l.k + '.mp3'));
  if (process.env.PRUNE) for (const f of fs.readdirSync(dir)) if (!said.has(f)) fs.unlinkSync(path.join(dir, f));
  const keep = new Set(fs.readdirSync(dir).filter(f => f.endsWith('.mp3')));
  fs.writeFileSync(path.join(ROOT, 'audio', id + '.js'),
    `/* clip list for ${deck}, generated by tools/den-voices.js */\nwindow.DEN_AUDIO_DIR='${rel}/${id}/';\nwindow.DEN_AUDIO=new Set(${JSON.stringify([...keep].map(f => f.slice(0, -4)).sort())});\n`);
  const kb = [...keep].reduce((n, f) => n + fs.statSync(path.join(dir, f)).size, 0) / 1024;
  console.log(`${deck}: ${lines.length} lines found, ${keep.size} clips, ${Math.round(kb)} KB`);
}

(async () => {
  const decks = process.argv.slice(2);
  if (!decks.length) { console.error('usage: node tools/den-voices.js <deck.html> ...'); process.exit(1); }
  if (!process.env.XAI_API_KEY && !process.env.DRY) { console.error('XAI_API_KEY is not set'); process.exit(1); }
  const browser = await chromium.launch();
  const queue = [...decks], failed = [];
  await Promise.all(Array.from({length: Math.min(+(process.env.JOBS || 6), decks.length)}, async () => {
    for (let d; (d = queue.shift());) { try { await doDeck(browser, d); } catch (e) { failed.push(d); console.error('FAILED', d, e.message); } }
  }));
  await browser.close();
  console.log(process.env.DRY ? `DRY: ${made} lines, ${chars} characters (about $${(chars * 15 / 1e6).toFixed(2)} at $15 per million)`
                              : `new clips: ${made}, characters sent to xAI: ${chars} (about $${(chars * 15 / 1e6).toFixed(2)})`);
  if (failed.length) { console.error('failed decks:', failed.join(' ')); process.exitCode = 1; }
})();
