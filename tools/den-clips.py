#!/usr/bin/env python3
"""Add (or refresh) short looping video clips over painted stills in a deck.

Each deck gets a small <script id="den-clips"> with its own map of  still image -> clip  (img/<dir>/v-<name>.mp4 plus
img/<dir>/v-<name>-poster.webp). Whenever the deck draws one of those stills as an SVG <image>, the clip is laid over it
at the same place, size, crop and clip-path: muted, inline, looping, with the poster underneath as the fallback.
With reduced motion the still stays. The block sits before the den-buddy tag (or stars.js), so the order stays
den-polish blocks, den-clips, den-buddy, stars.js (last). Run:
    python3 tools/den-clips.py
"""
import pathlib, re, json

ROOT = pathlib.Path(__file__).resolve().parent.parent

# deck -> {still as the deck writes it: clip path without extension}
CLIPS = {
    "stories/eagle-adv.html":   {"../img/eagle/peaksky.webp": "../img/eagle/v-peaksky"},
    "stories/leak-adv.html":    {"../img/leak/storm.webp": "../img/leak/v-storm"},
    "stories/trombone-adv.html": {"../img/trombone/night.webp": "../img/trombone/v-night"},
    "stories/talent-adv.html":  {"../img/talent/stage.webp": "../img/talent/v-stage"},
    "chinese/p2cn06.html":      {"../img/megan/nightmarket.webp": "../img/megan/v-nightmarket"},
    "science/sci-03.html":      {"../img/sci/v-sprout.webp": "../img/sci/v-sprout", "../img/sci/v-leaf-sun.webp": "../img/sci/v-leaf-sun",
                                 "../img/sci/v-dandelion.webp": "../img/sci/v-dandelion"},
    "science/sci-04.html":      {"../img/sci/v-butterfly.webp": "../img/sci/v-butterfly"},
    "science/sci-06.html":      {"../img/sci/v-handwash.webp": "../img/sci/v-handwash"},
    "chinese/p2cn02.html":      {"../img/cn/v-liondance.webp": "../img/cn/v-liondance"},
    "music/mus06.html":         {"../img/music/v-instruments.webp": "../img/music/v-instruments"},
    "science/sci-05.html":      {"../img/sci/v-heart.webp": "../img/sci/v-heart", "../img/sci/v-lungs.webp": "../img/sci/v-lungs", "../img/sci/v-handwash.webp": "../img/sci/v-handwash"},
    "science/sci-07.html":      {"../img/eco-mangrove.webp": "../img/v-mangrove"},
}

JS = r"""<script id="den-clips">
/* Short painted clips over their stills (generated by tools/den-clips.py): muted, inline, looping; the poster is the fallback; reduced motion keeps the still */
(()=>{const CLIPS=__MAP__,svg=document.getElementById('stage');if(!svg||matchMedia('(prefers-reduced-motion: reduce)').matches)return;
 const NS='http://www.w3.org/2000/svg',XH='http://www.w3.org/1999/xhtml';
 function up(){svg.querySelectorAll('image').forEach(im=>{const c=CLIPS[im.getAttribute('href')];if(!c||im.dataset.clip)return;im.dataset.clip='1';
  const fo=document.createElementNS(NS,'foreignObject');['x','y','width','height','clip-path','opacity','style','transform'].forEach(a=>{const v=im.getAttribute(a);if(v!==null)fo.setAttribute(a,v)});
  if(!fo.getAttribute('x'))fo.setAttribute('x','0');if(!fo.getAttribute('y'))fo.setAttribute('y','0');fo.setAttribute('aria-hidden','true');
  const v=document.createElementNS(XH,'video');v.muted=true;v.loop=true;v.autoplay=true;v.playsInline=true;v.preload='metadata';
  ['muted','playsinline','loop','autoplay'].forEach(a=>v.setAttribute(a,''));v.poster=c+'-poster.webp';v.src=c+'.mp4';
  const fit=(im.getAttribute('preserveAspectRatio')||'').includes('slice')?'cover':'contain';
  v.setAttribute('style',`width:100%;height:100%;object-fit:${fit};display:block`);fo.appendChild(v);im.after(fo);const p=v.play();if(p&&p.catch)p.catch(()=>{})})}
 new MutationObserver(up).observe(svg,{childList:true,subtree:true});up();})();
</script>
"""

def apply(rel, mapping):
    p = ROOT / rel
    s = p.read_text(encoding="utf-8")
    s = re.sub(r'<script id="den-clips">.*?</script>\n', "", s, flags=re.S)
    # sit after den-polish's blocks and before the buddy (tools/den-polish.py), with stars.js last
    k = s.find('<script id="den-buddy"')
    if k == -1:
        k = s.rfind('<script src="../stars.js"')
    assert k != -1, rel
    s = s[:k] + JS.replace("__MAP__", json.dumps(mapping)) + s[k:]
    p.write_text(s, encoding="utf-8")
    missing = [c for c in mapping.values() if not (p.parent / (c + ".mp4")).resolve().exists()]
    print(rel, "clips", len(mapping), "MISSING " + ", ".join(missing) if missing else "")

if __name__ == "__main__":
    for rel, m in CLIPS.items():
        apply(rel, m)
